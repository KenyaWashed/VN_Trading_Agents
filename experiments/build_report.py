import json
from pathlib import Path
from typing import Any


def _load_latest_runs(registry_path: Path) -> dict[str, dict[str, Any]]:
    if not registry_path.exists():
        raise FileNotFoundError(f"Experiment registry not found at {registry_path}. Run phases 1-4 first.")
    by_id: dict[str, dict[str, Any]] = {}
    with registry_path.open("r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            rec = json.loads(line)
            by_id[str(rec["run_id"])] = rec
    return by_id


def _fmt(val: Any, digits: int = 3) -> str:
    if isinstance(val, int | float):
        return f"{val:.{digits}f}"
    return "N/A"


